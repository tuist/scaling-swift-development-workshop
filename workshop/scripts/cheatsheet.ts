const fence = (body: string): string => "```sh\n" + body.trimEnd() + "\n```";

/** The rendered block for one task, without the surrounding markers. */
const block = (id: number): string => {
  const t = tasks.find((task) => task.id === id);
  if (!t) return "";
  const parts: string[] = [];
  const cmd = t.reveals?.find((r) => r.id === "commands");
  if (cmd) {
    const { shell, files } = extractFetchedFiles(stripAnsi(cmd.body));
    parts.push("**Type this live** (they mirror you):");
    parts.push(fence(shell));
    for (const f of files) {
      parts.push(`**\`${f.dest}\`** — type this out:`);
      parts.push("```" + f.lang + "\n" + f.content + "\n```");
    }
  }
  const show = showcase[id];
  if (show) {
    parts.push("**Show the solved state:**");
    parts.push(fence(show.join("\n")));
  }
  return parts.join("\n\n");
};

/**
 * Remove every generated block, so we always re-insert from a clean slate.
 *
 * Strips the old single appendix (CHEATSHEET markers) and every inline COMMANDS
 * block, however many there are. Running strip-then-insert makes the whole script
 * idempotent by construction: no matter what state the doc is in — one block per
 * task, none, or accidental duplicates — it ends with exactly one per task.
 */
const stripAllBlocks = (doc: string): string => {
  return doc
    .replace(/\n*<!-- CHEATSHEET:START[\s\S]*?<!-- CHEATSHEET:END -->\n*/g, "\n\n")
    .replace(/\n*<!-- COMMANDS:\d+:START[\s\S]*?<!-- COMMANDS:\d+:END -->\n*/g, "\n\n");
};

/**
 * The line where task `id`'s section ends: the next markdown heading (## or ###)
 * or `---` rule after its header. Returns [headerLine, endLine], or null if the
 * task has no section heading in the doc.
 *
 * The boundary requires two or more `#` so it never trips on a `# comment` line
 * inside a shell block — which is exactly the bug that duplicated blocks before.
 */
const sectionBounds = (lines: string[], id: number): [number, number] | null => {
  const header = new RegExp(`^#{2,3} Task ${id} [—-] `);
  const boundary = /^(#{2,3} |---\s*$)/;
  const headerLine = lines.findIndex((l) => header.test(l));
  if (headerLine === -1) return null;
  let end = lines.length;
  for (let i = headerLine + 1; i < lines.length; i++) {
    if (boundary.test(lines[i]!)) {
      end = i;
      break;
    }
  }
  return [headerLine, end];
};

/** Insert task `id`'s block at the end of its section. Assumes none exists yet. */
const insertBlock = (doc: string, id: number): { doc: string; placed: boolean } => {
  const rendered = `${startMark(id)}\n\n${block(id)}\n\n${endMark(id)}`;
  const lines = doc.split("\n");
  const bounds = sectionBounds(lines, id);
  if (!bounds) return { doc, placed: false };
  const [, end] = bounds;

  // Trim trailing blank lines inside the section, then insert with padding.
  let insertAt = end;
  while (insertAt > 0 && lines[insertAt - 1]!.trim() === "") insertAt--;
  lines.splice(insertAt, 0, "", rendered);
  return { doc: lines.join("\n"), placed: true };
};

const main = async (): Promise<void> => {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const facilitator = path.resolve(here, "../../maintainer/FACILITATOR.md");

  let doc: string;
  try {
    doc = await fs.readFile(facilitator, "utf8");
  } catch {
    console.error(`maintainer/FACILITATOR.md not found — nothing to update.`);
    process.exit(1);
    return;
  }

  doc = stripAllBlocks(doc);

  const missing: number[] = [];
  for (const t of tasks) {
    const result = insertBlock(doc, t.id);
    doc = result.doc;
    if (!result.placed) missing.push(t.id);
  }

  await fs.writeFile(facilitator, doc, "utf8");

  const rel = path.relative(process.cwd(), facilitator);
  if (missing.length) {
    console.log(`✔ Updated ${rel} (no section heading found for task ${missing.join(", ")} — skipped)`);
  } else {
    console.log(`✔ Updated the live commands under every task in ${rel}`);
  }
};

await main();
