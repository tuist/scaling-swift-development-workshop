const fence = (body: string): string => "```sh\n" + body.trimEnd() + "\n```";

const render = (): string => {
  const out: string[] = [];
  out.push(START);
  out.push("");
  out.push("## Live run-of-show — the exact commands");
  out.push("");
  out.push(
    "Generated from the task source, so it matches what the runner shows attendees " +
      "to the character. Regenerate with `mise run cheatsheet` after any task change.",
  );
  out.push("");
  out.push(
    "**The model:** you type, the room mirrors. Give them the *brief* and a few minutes " +
      "to attempt it before you reach for the commands — the struggle is where it sticks — " +
      "but don't make them earn every one. Reveal the hint when the room stalls, the " +
      "commands when you're ready to move, and the payoff reveal once they've measured.",
  );
  out.push("");

  for (const t of tasks) {
    out.push(`### Task ${t.id} — ${t.title}`);
    const reveals = (t.reveals ?? []).map((r) => revealLabel[r.id] ?? r.id).join(" · ");
    out.push(`_${t.stage} · reveals: ${reveals || "none"}_`);
    out.push("");

    const cmd = t.reveals?.find((r) => r.id === "commands");
    if (cmd) {
      out.push("**Type this live** (the room mirrors you):");
      out.push(fence(stripAnsi(cmd.body)));
      out.push("");
    }

    const show = showcase[t.id];
    if (show) {
      out.push("**Show the solved state:**");
      out.push(fence(show.join("\n")));
      out.push("");
    }
  }

  out.push(
    "> After showing a solved branch, return with `git checkout -` (and `tuist generate " +
      "--no-open` if you had regenerated). Commit or stash your own work first — the " +
      "generated `.xcworkspace` is gitignored, so checkouts stay clean.",
  );
  out.push("");
  out.push(END);
  return out.join("\n");
};

const main = async (): Promise<void> => {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const facilitator = path.resolve(here, "../../FACILITATOR.md");

  const section = render();
  let doc: string;
  try {
    doc = await fs.readFile(facilitator, "utf8");
  } catch {
    console.error(`FACILITATOR.md not found at ${facilitator} — nothing to update.`);
    process.exit(1);
    return;
  }

  const startAt = doc.indexOf(START);
  const endAt = doc.indexOf(END);
  let next: string;
  if (startAt !== -1 && endAt !== -1 && endAt > startAt) {
    next = doc.slice(0, startAt) + section + doc.slice(endAt + END.length);
  } else {
    next = doc.trimEnd() + "\n\n---\n\n" + section + "\n";
  }

  await fs.writeFile(facilitator, next, "utf8");
  console.log(`✔ Updated the live run-of-show in ${path.relative(process.cwd(), facilitator)}`);
};

await main();
