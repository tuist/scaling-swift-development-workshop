// Refreshes the live commands inside maintainer/FACILITATOR.md, placing each
// task's block *inside that task's section* so everything you need to run Task N
// sits under Task N's heading — not in an appendix 400 lines away.
//
//   mise run cheatsheet
//
// The commands come straight from the task source, so they match what the runner
// shows attendees to the character. Hand-transcribing them would rot the first
// time a flag changed, and this workshop has been bitten by drift more than once.
//
// It is self-installing and idempotent: the first run inserts a marked block at
// the end of each task's section; every run after that rewrites the block in
// place and leaves your prose untouched.

import { execFileSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { tasks } from "../src/tasks/index.js";

const stripAnsi = (s: string): string => s.replace(/\x1b\[[0-9;]*m/g, "");

const langFor = (dest: string): string => {
  switch (path.extname(dest).toLowerCase()) {
    case ".swift":
      return "swift";
    case ".sh":
    case ".bash":
      return "bash";
    case ".yml":
    case ".yaml":
      return "yaml";
    case ".json":
      return "json";
    default:
      return "";
  }
};

interface FetchedFile {
  dest: string;
  lang: string;
  content: string;
}

/**
 * Pull each `git show <ref>:<path> > <dest>` fetch out of the command body.
 *
 * The runner tells attendees to fetch big manifests from the solution branch —
 * lean for a terminal, but on the day the facilitator is typing these out live off
 * a second screen (an iPad mirroring the Mac). So in the facilitator doc (only) we
 * drop the fetch line to a one-line pointer and return each file's real contents
 * separately — rendered below as its own filename-labelled, syntax-highlighted
 * block you can read and transcribe. Prefer not to type? "Show the solved state"
 * checks the whole tree out instead.
 */
const extractFetchedFiles = (body: string): { shell: string; files: FetchedFile[] } => {
  const files: FetchedFile[] = [];
  // A big manifest fetched from the solution branch: git show <ref>:<src> > <dest>.
  let shell = body.replace(/^git show (\S+):(\S+) > (\S+)$/gm, (line, ref, src, dest) => {
    let content: string;
    try {
      content = execFileSync("git", ["show", `${ref}:${src}`], { encoding: "utf8" }).replace(/\n+$/, "");
    } catch {
      return `# (couldn't read ${ref}:${src} — is the branch present?)\n${line}`;
    }
    files.push({ dest, lang: langFor(dest), content });
    return `# Create ${dest} — full contents below.`;
  });
  // A small file the runner writes inline: cat > <dest> <<'DELIM' … DELIM.
  shell = shell.replace(/^cat > (\S+) <<'(\w+)'\n([\s\S]*?)\n\2$/gm, (_m, dest, _delim, content) => {
    files.push({ dest, lang: langFor(dest), content: (content as string).replace(/\n+$/, "") });
    return `# Create ${dest} — full contents below.`;
  });
  return { shell, files };
};

const startMark = (id: number): string =>
  `<!-- COMMANDS:${id}:START — generated by \`mise run cheatsheet\`, do not edit by hand -->`;
const endMark = (id: number): string => `<!-- COMMANDS:${id}:END -->`;

